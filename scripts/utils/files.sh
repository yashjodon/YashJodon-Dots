#!/usr/bin/env bash

# ==========================================================
# YashJodon-Dots
# files.sh
#
# Filesystem helper library
# ==========================================================

[[ "${YJD_FILES_LOADED:-0}" == "1" ]] && return 0
readonly YJD_FILES_LOADED=1

# ----------------------------------------------------------
# File Checks
# ----------------------------------------------------------

yjd_file_exists() {
    [[ -f "$1" ]]
}

yjd_dir_exists() {
    [[ -d "$1" ]]
}

# ----------------------------------------------------------
# Directory
# ----------------------------------------------------------

yjd_safe_mkdir() {

    local dir="$1"

    mkdir -p "$dir"

}

# ----------------------------------------------------------
# Backup
# ----------------------------------------------------------

yjd_backup_file() {

    local file="$1"

    if [[ ! -f "$file" ]]; then
        return 1
    fi

    cp -a "$file" "${file}.bak"
}

# ----------------------------------------------------------
# Copy
# ----------------------------------------------------------

yjd_safe_copy() {

    local source="$1"
    local destination="$2"

    cp -a "$source" "$destination"
}

# ----------------------------------------------------------
# Move
# ----------------------------------------------------------

yjd_safe_move() {

    local source="$1"
    local destination="$2"

    mv "$source" "$destination"
}

# ----------------------------------------------------------
# Remove
# ----------------------------------------------------------

yjd_safe_remove() {

    local target="$1"

    rm -rf "$target"
}

# ----------------------------------------------------------
# Symlink
# ----------------------------------------------------------

yjd_create_symlink() {

    local source="$1"
    local target="$2"

    ln -sfn "$source" "$target"
}